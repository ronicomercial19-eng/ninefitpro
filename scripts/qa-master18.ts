import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { durationMinutes, matchesCatalog, type CatalogFilters } from '../src/services/catalogFilters';
import { weeklyAdherence } from '../src/services/athleteCardRules';
import { businessDate } from '../src/services/dailyContextRules';
import { missingPhysiologyReply } from '../supabase/functions/_shared/ronSnapshotGuard';

const empty: CatalogFilters = { search: '', category: '', level: '', duration: '', objective: '', equipment: '' };
assert.equal(durationMinutes('20:30'), 20.5);
assert.equal(durationMinutes('01:00:00'), 60);
assert.equal(durationMinutes('20:99'), null);
assert.equal(durationMinutes('não informado'), null);
assert.equal(matchesCatalog({ title: 'Alongamento de pescoço', duration: null }, { ...empty, search: 'pescoco' }), true);
assert.equal(matchesCatalog({ title: 'Aula', duration: null }, { ...empty, duration: 'short' }), false);
assert.equal(matchesCatalog({ title: 'Aula', duration: null }, { ...empty, duration: '__unknown' }), true);
assert.equal(matchesCatalog({ title: 'Aula', equipment: ['halteres', 'elástico'] }, { ...empty, equipment: 'elástico' }), true);
assert.equal(matchesCatalog({ title: 'Aula', category: 'Yoga', level: 'Iniciante', duration: '30 min' }, { ...empty, category: 'Yoga', level: 'Avançado' }), false);
assert.equal(weeklyAdherence([{ date: '2026-10-10', status: 'planned', exerciseCount: 9 }], '2026-10-11'), 0);
assert.equal(weeklyAdherence([{ date: '2026-10-12', status: 'planned', exerciseCount: 9 }], '2026-10-11'), null);
assert.equal(weeklyAdherence([{ date: '2026-10-09', status: 'completed', exerciseCount: 9 }, { date: '2026-10-10', status: 'planned', exerciseCount: 9 }], '2026-10-11'), 50);
assert.equal(businessDate(new Date('2026-10-12T01:00:00Z')), '2026-10-11');
const now = Date.parse('2026-10-11T15:00:00Z');
const available = { value: 45, status: 'available', observed_at: '2026-10-11T12:00:00Z' };
assert.ok(missingPhysiologyReply('Como está meu HRV?', null, now));
assert.ok(missingPhysiologyReply('Meu recovery?', { vitals: { hrv: { ...available, status: 'stale' } } }, now));
assert.ok(missingPhysiologyReply('Meu recovery?', { vitals: { hrv: { ...available, observed_at: '2026-10-08T12:00:00Z' } } }, now));
assert.ok(missingPhysiologyReply('Meu BPM?', { vitals: { heart_rate: { ...available, observed_at: '2026-10-12T12:00:00Z' } } }, now));
assert.equal(missingPhysiologyReply('Meu HRV?', { vitals: { hrv: available } }, now), null);
assert.equal(missingPhysiologyReply('Olá, RON', null, now), null);
const routes = readFileSync('src/App.tsx', 'utf8');
assert.match(routes, /path="\/9fit\/home" element={<Navigate to="\/9fit\/os" replace/);
const metrics = readFileSync('src/components/9fit/HubFloatingMetrics.tsx', 'utf8');
assert.match(metrics, /\/9fit\/dieta\?action=water#hydration/);
assert.match(metrics, /vital: 'hrv'/);
assert.match(metrics, /vital: 'heart_rate'/);
assert.match(metrics, /\/9fit\/dieta\?action=log/);
console.log('QA MASTER: filtros, ausência de dados, aderência, data local, bloqueio fisiológico e destinos de registro passaram.');
