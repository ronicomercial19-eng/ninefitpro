const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const source = path.resolve(__dirname, '../src/services/assessmentMetrics.ts');
const compiled = ts.transpileModule(fs.readFileSync(source, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const moduleUnderTest = new Module(source); moduleUnderTest._compile(compiled, source);
const { metricValue, trustFor, metricRecord, compareRow, officialRows, goalProjection, assessmentMetrics, referenceFor } = moduleUnderTest.exports;
const metric = assessmentMetrics.find(m => m.key === 'rm1_empurrar_superior');
const row = (id, date, kg, overrides = {}) => ({ id, data_avaliacao: date, origem: 'manual', oficial: true, score_global: 60, rm1_empurrar_superior: kg, dados_adicionais: {}, ...overrides });
const history = [row('a','2026-01-01',60), row('b','2026-02-01',65), row('c','2026-03-01',70), row('d','2026-04-01',75)];
assert.equal(metricValue(row('x','2026-01-01',null),metric.key), null, 'missing measurement must stay null');
assert.equal(metricValue(row('x','2026-01-01',0),metric.key), 0, 'measured zero must not disappear');
assert.equal(officialRows([history[0], row('self','2026-02-02',200,{origem:'avaliacao_guiada',oficial:false})]).length, 1);
assert.equal(compareRow(history,history[3],'primeira').id,'a');
assert.equal(compareRow(history,history[3],'anterior').id,'c');
assert.equal(compareRow([history[0]],history[0],'anterior'),null, 'single assessment has no comparison');
assert.equal(compareRow([],history[0],'primeira'),null, 'empty history');
assert.equal(metricRecord(history[3],metric,history),true);
assert.equal(metricRecord(row('self','2026-05-01',200,{origem:'avaliacao_guiada',oficial:false}),metric,history),false);
const estimated = row('estimated','2026-05-01',200,{dados_adicionais:{confianca:{[metric.key]:'ESTIMADO'}}});
assert.equal(trustFor(estimated,metric),'ESTIMADO');
assert.equal(metricRecord(estimated,metric,history),false,'estimate cannot be an official record');
const vo2 = assessmentMetrics.find(m=>m.key==='vo2_estimado');
assert.equal(trustFor(row('vo2','2026-01-01',60,{dados_adicionais:{vo2_estimado:44,confianca:{vo2_estimado:'CONFIRMADO'}}}),vo2),'ESTIMADO');
const goal={metrica:metric.key,exercicio:'Supino',valor_meta:90};
assert.equal(goalProjection(goal,history.slice(0,3)).estimate,null,'three points cannot project a date');
const projection=goalProjection(goal,history);
assert.ok(projection.estimate && projection.estimate.from < projection.estimate.to,'four distinct measured dates produce an uncertainty range');
assert.equal(goalProjection(goal,[...history.slice(0,3),{...history[2],id:'duplicate'}]).estimate,null,'same-day duplicate is not a fourth assessment');
assert.equal(referenceFor(history[0],metric,[]),null,'no reference data means no invented band');
assert.equal(referenceFor(history[0],metric,[{teste:metric.key,unidade:'kg',protocolo:'test',fonte:'https://example.test/protocol',limites:[{min:0,rotulo:'bom'}]}]),null,'unidentified protocol cannot use a band');
console.log('Assessment acceptance rules: 16 checks passed (0/1/multiple records, trust, official separation, projection and references).');
